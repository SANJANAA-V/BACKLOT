import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # repo root, so imports work on any host

import pandas as pd  # noqa: E402
import streamlit as st  # noqa: E402

from frontend.client import make_client  # noqa: E402

st.set_page_config(page_title="BACKLOT", page_icon="📦", layout="wide")


@st.cache_resource
def get_client():
    return make_client()


client, labels, mode = get_client()
st.title("BACKLOT")
st.caption("The intelligence layer behind product returns and recovery")
if mode == "demo":
    st.warning("DEMO MODE: all data is SYNTHETIC; image analysis is SIMULATED (no pixels are analysed); "
               "the report is deterministic unless ANTHROPIC_API_KEY is set. Scores are not real-world fraud detection.")

ids = client.get("/returns").json().get("return_ids", [])
with st.sidebar:
    st.header("Find a return")
    sample = st.selectbox("Sample cases", [""] + ids, format_func=lambda r: f"{r} ({labels[r]})" if r in labels else (r or "-"))
    typed = st.text_input("Return ID", value="")
    rid = (typed or sample).strip()
    run = st.button("Run investigation", type="primary", disabled=not rid)

if not rid:
    st.info("Pick a sample case or type a return ID.")
    st.stop()

if run:
    r = client.post(f"/returns/{rid}/investigate")
    if r.status_code != 200:
        st.error(f"Investigation failed: {r.status_code} {r.text}")
        st.stop()
resp = client.get(f"/returns/{rid}/investigation")
if resp.status_code == 404:
    st.info("No investigation yet for this return. Click 'Run investigation'.")
    st.stop()
b = resp.json()
rec, dec, rep = b["reconciliation"], b["decision"], b["report"]

c1, c2, c3, c4 = st.columns(4)
c1.metric("Evidence completeness", rec["completeness"]["status"], f"{rec['completeness']['ratio']:.0%} present", delta_color="off")
c2.metric("Risk score (synthetic model)", f"{b['risk']['score']:.2f}" if b["risk"] else "n/a",
          "flagged" if b["risk"] and b["risk"]["flagged"] else "not flagged", delta_color="off")
c3.metric("Recommended action", dec["action"])
c4.metric("Human review", b["review_status"])
st.caption(rec["disclaimer"])

t_time, t_find, t_img, t_pol, t_rep, t_dec, t_aud = st.tabs(
    ["Timeline", "Findings", "Image evidence", "Policies", "Investigation report", "Recovery decision", "Audit history"])

with t_time:
    st.dataframe(pd.DataFrame(rec["timeline"]), use_container_width=True, hide_index=True)
    st.write("Missing evidence:", ", ".join(rec["completeness"]["missing"]) or "none")
    dot = ["digraph G { rankdir=LR; node [shape=box, fontsize=10];"]
    for n in rec["graph"]["nodes"]:
        color = {"return": "lightblue", "event": "white", "finding": "orange"}[n["kind"]]
        dot.append(f'"{n["id"]}" [label="{n["label"]}", style=filled, fillcolor={color}];')
    for e in rec["graph"]["edges"]:
        if e["relation"] in ("supported_by", "conflicts_with"):
            dot.append(f'"{e["source"]}" -> "{e["target"]}" [label="{e["relation"]}", fontsize=8];')
    st.graphviz_chart("\n".join(dot) + "}")

with t_find:
    if b["risk"]:
        st.subheader("Risk contributing factors")
        st.dataframe(pd.DataFrame(b["risk"]["contributions"]), hide_index=True)
        st.caption(b["risk"]["disclaimer"])
    st.subheader("Detected inconsistencies")
    for f in rec["findings"] or []:
        with st.expander(f"{f['severity']} / {f['confidence']} confidence - {f['type']}: {f['summary']}"):
            st.write("Supporting events:", f["supporting_event_ids"])
            if f["conflicting_event_ids"]:
                st.write("Conflicts with:", f["conflicting_event_ids"])
            st.write("Possible benign explanations:", f["benign_explanations"])
    if not rec["findings"]:
        st.success("No inconsistencies found.")

with t_img:
    if b["vision"]:
        st.caption(b["vision"]["notice"])
        st.dataframe(pd.DataFrame(b["vision"]["findings"]).drop(columns=["verified"]), hide_index=True)
        for d in b["vision"]["differences"]:
            st.warning(f"{d['kind']}: {d['detail']} (confidence {d['confidence']}; unverified)")
    else:
        st.info("No image analysis was run.")

with t_pol:
    for p in b["policy_references"]:
        with st.expander(f"{p['chunk_id']} - {p['title']} ({p['doc']} v{p['version']}, similarity {p['score']})"):
            st.write(p["text"])

with t_rep:
    st.caption(f"Generated by: {b['report_meta']['generated_by']}"
               + (f" (fallback reason: {b['report_meta']['fallback_reason']})" if b["report_meta"]["fallback_reason"] else ""))
    st.write(rep["investigation_summary"])
    st.subheader("Finding explanations")
    for e in rep["evidence_findings"]:
        st.write(f"- `{e['finding_id']}`: {e['explanation']}")
    st.write("Policy references:", rep["relevant_policy_references"])
    st.write("Uncertainty:", rep["uncertainty"])
    st.write("Supporting event ids:", rep["supporting_event_ids"])

with t_dec:
    st.subheader(f"{dec['action']}  (human review required: {dec['human_review_required']})")
    st.write(dec["reasons"])
    st.dataframe(pd.DataFrame([{"rule": t["rule_id"], "fired": t["fired"], "description": t["description"]}
                               for t in dec["rule_trace"]]), hide_index=True)
    st.json(dec["inputs"], expanded=False)
    st.caption(dec["note"])
    st.subheader("Reviewer decision")
    with st.form("review"):
        who = st.text_input("Reviewer name")
        outcome = st.selectbox("Outcome", ["CONFIRMED", "OVERRIDDEN", "NEEDS_MORE_INFO"])
        final = st.selectbox("Final action (required if overridden)", ["", "RESALE", "REFURBISH", "REPAIR", "LIQUIDATE", "RECYCLE", "HUMAN_REVIEW"])
        note = st.text_area("Note")
        if st.form_submit_button("Record review"):
            r = client.post(f"/returns/{rid}/review", json={"reviewer": who, "outcome": outcome,
                                                            "final_action": final or None, "note": note})
            st.success(f"Recorded. Status: {r.json()['review_status']}") if r.status_code == 200 else st.error(r.text)

with t_aud:
    entries = client.get(f"/returns/{rid}/audit").json()["entries"]
    st.dataframe(pd.DataFrame([{"id": e["id"], "time": e["created_at"], "actor": e["actor"], "action": e["action"],
                                "detail": str(e["detail"])[:300]} for e in entries]), use_container_width=True, hide_index=True)
