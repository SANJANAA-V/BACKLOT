"""Train on SYNTHETIC data, save the model + metrics, regenerate docs/evaluation.md."""
import argparse
import json
from pathlib import Path

from services.ml_worker.training import train


def _row(name, m):
    c = m["confusion_matrix"]
    return (f"| {name} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} | {m['pr_auc']:.3f} | "
            f"{c['tn']} | {c['fp']} | {c['fn']} | {c['tp']} |")


def render(r: dict) -> str:
    d, hdr = r["data"], "| | precision | recall | F1 | PR-AUC | TN | FP | FN | TP |\n|---|---|---|---|---|---|---|---|---|"
    imp = "\n".join(f"| {k} | {v:.4f} |" for k, v in r["permutation_importance_val"].items())
    flag = "\n".join(f"| {k} | {v:.0%} |" for k, v in r["test_by_scenario_flag_rate"].items())
    return f"""# Evaluation (auto-generated by `scripts/train_model.py`; do not edit by hand)

> **All numbers below are from SYNTHETIC data with scenario-derived labels. They say nothing about
> real-world fraud detection performance.** Labels come from the same scenario definitions that generate the
> features, so a good score mostly shows the pipeline works, not that the problem is solved.

Data: seed {d['seed']}, {d['n_returns']} returns, split train/val/test = {d['split_sizes']}.
Test prevalence of the positive class: {d['prevalence']['test']:.3f}.
Label noise (arbitrary, not measured): {d['label_noise']['anomalous_to_normal']:.0%} of anomalous scenarios
labelled normal, {d['label_noise']['normal_to_anomalous']:.0%} of normal-looking returns labelled anomalous.

Model selection on validation PR-AUC: {json.dumps(r['validation_pr_auc'])} -> chosen **{r['chosen_model']}**.
The decision threshold ({r['test_model']['threshold']:.3f}) was picked on validation to maximise F1; the test split was scored once.

## Test results, noisy labels (the primary evaluation)
{hdr}
{_row('ML model', r['test_model'])}
{_row('Rule baseline', r['test_rule_baseline'])}

## Test results against the noise-free scenario labels (ceiling check)
{hdr}
{_row('ML model', r['test_model_vs_clean_scenario_labels'])}
{_row('Rule baseline', r['test_rule_vs_clean_scenario_labels'])}

## How to read this
- The rule baseline is a few hand-written thresholds on the same features. It matches or beats the ML model here:
  the synthetic labels are a deterministic function of those features, so there is nothing for ML to add.
  Whether ML helps on real returns is untested.
- Remaining errors under noisy labels come from the injected label noise, not from model weakness.
- PR-AUC should be compared with the prevalence ({d['prevalence']['test']:.3f}), the score of a random ranker.

## Validation permutation importance (PR-AUC drop)
| feature | importance |
|---|---|
{imp}

`prior_returns_90d` is statistically independent of the labels by construction; a small non-zero value is noise.
Missing-evidence features learn "not anomalous" because the scenario labels treat incomplete evidence as a
review case rather than an anomaly. That is a labelling choice; completeness is handled separately in the decision engine.

## Test flag rate by scenario
| scenario | flagged |
|---|---|
{flag}
"""


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--n", type=int, default=5000)
    ap.add_argument("--out", default="models")
    a = ap.parse_args()
    model, report = train(a.seed, a.n)
    out = Path(a.out); out.mkdir(exist_ok=True)
    model.save(out / "risk_model.joblib")
    (out / "metrics.json").write_text(json.dumps(report, indent=2))
    Path("docs/evaluation.md").write_text(render(report))
    print(f"[SYNTHETIC] saved {out/'risk_model.joblib'}; chosen={report['chosen_model']}; "
          f"test F1={report['test_model']['f1']:.3f} PR-AUC={report['test_model']['pr_auc']:.3f}")
